#!/usr/bin/env python3
"""Run every lemma of a Tamarin theory one at a time, under a time cap.

Usage: run-lemmas.py THEORY... [--lemma-cap SECONDS] [--suite-cap SECONDS]
                               [--cores N] [--heap SIZE] [--only PREFIX ...]
                               [--summary FILE] [--check FILE]

Each lemma is proved in its own tamarin-prover process, with goals ranked by
the oracle formal/tamarin/oracles/aitp.py, so that one lemma's
cap does not affect another. The prover runs in its own process group, limited
to --cores GHC threads (default 2) and a --heap GHC heap cap (default 4g)
at low priority, and the whole group
(tamarin-prover and its maude children) is killed when a lemma hits its cap or
the runner is interrupted, so no prover outlives the run. The result is one of:

  verified      all-traces lemma proved, or exists-trace lemma found a trace
  falsified     all-traces lemma has a counterexample, or exists-trace lemma
                has no trace
  inconclusive  the lemma did not finish within the cap (never "verified")

--summary writes the results table (formal/results/summary.md). --check
compares the theory, lemma, result and Tamarin columns of a committed
table with this run; wall time and spec commit are informational.

Exit status is 0 only if every all-traces lemma is verified and every
exists-trace lemma finds a trace, the pinned versions match, the suite
finishes within its cap, and (with --check) nothing drifted.
"""

import argparse
import os
import signal
import re
import shutil
import subprocess
import sys
import time

PINNED_TAMARIN = "1.12.0"
PINNED_MAUDE = "3.5.1"


def versions():
    out = subprocess.run(["tamarin-prover", "--version"], capture_output=True,
                         text=True).stdout
    t = re.search(r"tamarin-prover (\S+?),", out)
    m = subprocess.run(["maude", "--version"], capture_output=True,
                       text=True).stdout.strip()
    return (t.group(1) if t else "unknown"), m


def lemmas(theory, only):
    names = []
    with open(theory, encoding="utf-8") as fh:
        for line in fh:
            m = re.match(r"\s*lemma\s+([A-Za-z0-9_]+)", line)
            if m and (not only or any(m.group(1).startswith(p) for p in only)):
                names.append(m.group(1))
    return names


def kill_group(proc):
    try:
        os.killpg(proc.pid, signal.SIGKILL)
    except (ProcessLookupError, PermissionError):
        pass
    proc.wait()


ORACLE = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "tamarin", "oracles", "aitp.py")


def prove(theory, name, cap, cores, heap, oracle=ORACLE):
    cmd = ["nice", "-n", "10", "tamarin-prover", "--derivcheck-timeout=0",
           "--heuristic=o", f"--oraclename={oracle}",
           f"--prove={name}", theory, "+RTS", f"-N{cores}", f"-M{heap}",
           "-RTS"]
    start = time.monotonic()
    proc = subprocess.Popen(cmd, stdout=subprocess.PIPE,
                            stderr=subprocess.DEVNULL, text=True,
                            start_new_session=True)
    try:
        out, _ = proc.communicate(timeout=cap)
    except subprocess.TimeoutExpired:
        kill_group(proc)
        return "inconclusive", None, time.monotonic() - start
    except BaseException:
        kill_group(proc)
        raise
    finally:
        # maude children can outlive a finished tamarin-prover too
        if proc.poll() is not None:
            try:
                os.killpg(proc.pid, signal.SIGKILL)
            except (ProcessLookupError, PermissionError):
                pass
    elapsed = time.monotonic() - start
    m = re.search(rf"^\s*{re.escape(name)} \((all-traces|exists-trace)\): "
                  r"(verified|falsified|analysis incomplete)[^\n]*?"
                  r"(?:\((\d+) steps\))?$", out, re.M)
    if not m:
        return "error", None, elapsed
    kind, res, steps = m.group(1), m.group(2), m.group(3)
    if res == "analysis incomplete":
        return "inconclusive", kind, elapsed
    if kind == "exists-trace":
        res = "verified" if res == "verified" else "falsified"
    return res, kind, elapsed


def spec_commit():
    out = subprocess.run(["git", "rev-parse", "--short=12", "HEAD"],
                         capture_output=True, text=True)
    return out.stdout.strip() or "unknown"


HEADER = ("| theory | lemma | result | Tamarin | spec commit | wall time |\n"
          "|---|---|---|---|---|---|\n")


def write_summary(path, rows, tv, total):
    commit = spec_commit()
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# Tamarin results\n\n"
                 "Generated by `make formal` (formal/run-lemmas.py). The "
                 "theory, lemma, result and Tamarin columns are checked in "
                 "CI; spec commit and wall time are informational.\n\n")
        fh.write(HEADER)
        for theory, name, res, elapsed in rows:
            fh.write(f"| {theory} | {name} | {res} | {tv} | {commit} | "
                     f"{elapsed:.1f}s |\n")
        fh.write(f"\nSuite wall time: {total:.1f}s.\n")


def checked_columns(path):
    rows = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) == 6 and cells[0] not in ("theory", "---"):
                rows.append(tuple(cells[:4]))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("theories", nargs="+")
    ap.add_argument("--lemma-cap", type=int, default=180)
    ap.add_argument("--suite-cap", type=int, default=1080)
    ap.add_argument("--cores", type=int, default=2)
    ap.add_argument("--heap", default="4g",
                    help="GHC heap cap per prover (+RTS -M), default 4g")
    ap.add_argument("--only", nargs="*", default=[])
    ap.add_argument("--oracle", default=ORACLE,
                    help="goal-ranking oracle, default tamarin/oracles/aitp.py")
    ap.add_argument("--summary",
                    help="write the results table to this Markdown file")
    ap.add_argument("--check",
                    help="compare theory, lemma, result and Tamarin version "
                         "with this committed summary; fail on any drift")
    args = ap.parse_args()

    if not shutil.which("tamarin-prover"):
        print("tamarin-prover not found; see formal/README.md", file=sys.stderr)
        return 2
    tv, mv = versions()
    print(f"Tamarin {tv} (pinned {PINNED_TAMARIN}), Maude {mv} "
          f"(pinned {PINNED_MAUDE})")
    ok = tv == PINNED_TAMARIN and mv == PINNED_MAUDE
    if not ok:
        print("version mismatch with the pin", file=sys.stderr)

    print(f"{'lemma':<40} {'result':<13} {'time':>8}")
    rows = []
    suite_start = time.monotonic()
    for theory in args.theories:
        tname = os.path.basename(theory)
        print(f"# {tname}")
        for name in lemmas(theory, args.only):
            res, _, elapsed = prove(theory, name, args.lemma_cap, args.cores,
                                    args.heap, os.path.abspath(args.oracle))
            print(f"{name:<40} {res:<13} {elapsed:7.1f}s", flush=True)
            rows.append((tname, name, res, elapsed))
            if res != "verified":
                ok = False
    total = time.monotonic() - suite_start
    print(f"{'suite':<40} {'':<13} {total:7.1f}s")
    if total > args.suite_cap:
        print(f"suite exceeded its {args.suite_cap}s cap", file=sys.stderr)
        ok = False
    if args.summary:
        write_summary(args.summary, rows, tv, total)
    if args.check:
        want = checked_columns(args.check)
        got = [(t, n, r, tv) for t, n, r, _ in rows]
        if want != got:
            ok = False
            print(f"results drift from {args.check}:", file=sys.stderr)
            for row in sorted(set(want) ^ set(got)):
                side = "committed" if row in want else "this run"
                print(f"  {side}: {' | '.join(row)}", file=sys.stderr)
        else:
            print(f"results match {args.check}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
