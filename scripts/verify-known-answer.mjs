#!/usr/bin/env node
//
// Executable verification of every pinned cryptographic value under
// schemas/conformance/known-answer/.
//
// `scripts/validate-json.sh` checks that these files are well-formed JSON and
// that they match their schemas. Nothing checked that the values inside them
// were *correct*: no pinned canonical byte sequence was ever recomputed and no
// pinned signature was ever verified. This script closes that gap.
//
// Zero dependencies by design. Node's built-in `crypto` verifies Ed25519 and
// ECDSA-P256 natively, and Node 20+ is already the CI runtime for `ajv`. The
// off-the-shelf JOSE smoke test in known-answer/README.md uses this same API,
// so this extends a pattern the repo already sanctions rather than adding a
// toolchain.
//
// Node's `crypto.verify` is never the only thing deciding a result. The
// RFC-AITP-0001 §5.4.7 strictness rules (Ed25519: S < L, canonical point
// encodings, no small-order public key, cofactorless equation; P-256: R and S
// in [1, n-1], S <= n/2) are checked here in BigInt arithmetic, and the
// verification equation for both algorithms is evaluated in BigInt too. A
// signature is accepted only when the BigInt result and `crypto.verify` agree;
// a disagreement is a hard failure, not a vote. Rejection never depends on how
// a particular OpenSSL build treats high-S or small-order inputs, which differs
// across the Node versions CI and contributors run.
//
// Deliberately independent of both reference implementations: the vectors are
// generated by `scripts/regen-known-answer.py` (which drives aitp-verifier-py)
// and verified here by a separate JCS + JOSE implementation. Bytes produced by
// one implementation and verified by another is the whole point.
//
// Usage:  node scripts/verify-known-answer.mjs [--quiet]
// Exit:   0 = every pinned value reproduced; non-zero = at least one mismatch.

import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash, createPublicKey, createPrivateKey, verify as cryptoVerify } from 'node:crypto';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const KAT = join(ROOT, 'schemas/conformance/known-answer');
const SIGNED = join(KAT, 'signed-examples');
const QUIET = process.argv.includes('--quiet');

let checks = 0;
const failures = [];

function check(name, fn) {
  checks += 1;
  try {
    fn();
    if (!QUIET) console.log(`  ok   ${name}`);
  } catch (err) {
    failures.push(`${name}: ${err.message}`);
    console.log(`  FAIL ${name}\n         ${err.message}`);
  }
}

function eq(actual, expected, what) {
  if (actual !== expected) {
    throw new Error(`${what} mismatch\n         got      ${actual}\n         expected ${expected}`);
  }
}

// ── RFC 8785 (JCS) canonicalization ──────────────────────────────────────────
//
// Object members are sorted by the UTF-16 code units of their names, which is
// exactly what JavaScript's `<` on strings compares, so a plain sort is correct.
// Strings use JSON.stringify, whose escaping is the serialization RFC 8785
// specifies. Numbers are the one place a naive implementation silently produces
// wrong bytes, so anything that is not a safe integer is a hard error rather
// than a guess — a spec repository must never emit "probably right" canonical
// bytes.

function jcs(value, path = '$') {
  if (value === null) return 'null';
  const t = typeof value;
  if (t === 'boolean') return value ? 'true' : 'false';
  if (t === 'string') return JSON.stringify(value);
  if (t === 'number') {
    if (!Number.isInteger(value)) {
      throw new Error(
        `${path}: non-integer number ${value}. RFC 8785 number serialization for ` +
        `non-integers is not implemented here; add it deliberately rather than ` +
        `letting this script emit bytes it has not been proven to get right.`);
    }
    if (!Number.isSafeInteger(value)) throw new Error(`${path}: integer ${value} exceeds 2^53-1`);
    return String(value);
  }
  if (Array.isArray(value)) {
    return '[' + value.map((v, i) => jcs(v, `${path}[${i}]`)).join(',') + ']';
  }
  if (t === 'object') {
    const keys = Object.keys(value).sort();
    return '{' + keys.map((k) => `${JSON.stringify(k)}:${jcs(value[k], `${path}.${k}`)}`).join(',') + '}';
  }
  throw new Error(`${path}: value of type ${t} has no JCS serialization`);
}

const utf8 = (s) => Buffer.from(s, 'utf8');
const sha256 = (buf) => createHash('sha256').update(buf).digest();
const b64uEncode = (buf) => Buffer.from(buf).toString('base64url');

function b64uDecode(s, expectedLen, what) {
  if (typeof s !== 'string' || /[^A-Za-z0-9_-]/.test(s)) {
    throw new Error(`${what}: not unpadded base64url: ${JSON.stringify(s)}`);
  }
  const buf = Buffer.from(s, 'base64url');
  if (expectedLen !== undefined && buf.length !== expectedLen) {
    throw new Error(`${what}: decoded to ${buf.length} bytes, expected ${expectedLen}`);
  }
  return buf;
}

