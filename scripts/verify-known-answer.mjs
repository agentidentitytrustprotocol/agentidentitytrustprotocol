#!/usr/bin/env node
//
// Executable verification of every pinned cryptographic value under
// schemas/conformance/known-answer/.
//
// `scripts/validate-json.sh` checks that these files are well-formed JSON and
// that they match their schemas. Nothing checked that the values inside them
// were *correct*: no pinned canonical byte sequence was ever recomputed and no
// pinned signature was ever verified. This script closes that gap.
//
// Zero dependencies by design. Node's built-in `crypto` verifies Ed25519 and
// ECDSA-P256 natively, and Node 20+ is already the CI runtime for `ajv`. The
// off-the-shelf JOSE smoke test in known-answer/README.md uses this same API,
// so this extends a pattern the repo already sanctions rather than adding a
// toolchain.
//
// Deliberately independent of both reference implementations: the vectors are
// generated by `scripts/regen-known-answer.py` (which drives aitp-verifier-py)
// and verified here by a separate JCS + JOSE implementation. Bytes produced by
// one implementation and verified by another is the whole point.
//
// Usage:  node scripts/verify-known-answer.mjs [--quiet]
// Exit:   0 = every pinned value reproduced; non-zero = at least one mismatch.

import { readFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash, createPublicKey, createPrivateKey, verify as cryptoVerify } from 'node:crypto';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const KAT = join(ROOT, 'schemas/conformance/known-answer');
const SIGNED = join(KAT, 'signed-examples');
const QUIET = process.argv.includes('--quiet');

let checks = 0;
const failures = [];

function check(name, fn) {
  checks += 1;
  try {
    fn();
    if (!QUIET) console.log(`  ok   ${name}`);
  } catch (err) {
    failures.push(`${name}: ${err.message}`);
    console.log(`  FAIL ${name}\n         ${err.message}`);
  }
}

function eq(actual, expected, what) {
  if (actual !== expected) {
    throw new Error(`${what} mismatch\n         got      ${actual}\n         expected ${expected}`);
  }
}

// ── RFC 8785 (JCS) canonicalization ──────────────────────────────────────────
//
// Object members are sorted by the UTF-16 code units of their names, which is
// exactly what JavaScript's `<` on strings compares, so a plain sort is correct.
// Strings use JSON.stringify, whose escaping is the serialization RFC 8785
// specifies. Numbers are the one place a naive implementation silently produces
// wrong bytes, so anything that is not a safe integer is a hard error rather
// than a guess — a spec repository must never emit "probably right" canonical
// bytes.

function jcs(value, path = '$') {
  if (value === null) return 'null';
  const t = typeof value;
  if (t === 'boolean') return value ? 'true' : 'false';
  if (t === 'string') return JSON.stringify(value);
  if (t === 'number') {
    if (!Number.isInteger(value)) {
      throw new Error(
        `${path}: non-integer number ${value}. RFC 8785 number serialization for ` +
        `non-integers is not implemented here; add it deliberately rather than ` +
        `letting this script emit bytes it has not been proven to get right.`);
    }
    if (!Number.isSafeInteger(value)) throw new Error(`${path}: integer ${value} exceeds 2^53-1`);
    return String(value);
  }
  if (Array.isArray(value)) {
    return '[' + value.map((v, i) => jcs(v, `${path}[${i}]`)).join(',') + ']';
  }
  if (t === 'object') {
    const keys = Object.keys(value).sort();
    return '{' + keys.map((k) => `${JSON.stringify(k)}:${jcs(value[k], `${path}.${k}`)}`).join(',') + '}';
  }
  throw new Error(`${path}: value of type ${t} has no JCS serialization`);
}

const utf8 = (s) => Buffer.from(s, 'utf8');
const sha256 = (buf) => createHash('sha256').update(buf).digest();
const b64uEncode = (buf) => Buffer.from(buf).toString('base64url');

function b64uDecode(s, expectedLen, what) {
  if (typeof s !== 'string' || /[^A-Za-z0-9_-]/.test(s)) {
    throw new Error(`${what}: not unpadded base64url: ${JSON.stringify(s)}`);
  }
  const buf = Buffer.from(s, 'base64url');
  if (expectedLen !== undefined && buf.length !== expectedLen) {
    throw new Error(`${what}: decoded to ${buf.length} bytes, expected ${expectedLen}`);
  }
  return buf;
}

// ── keys ─────────────────────────────────────────────────────────────────────

const ed25519PublicFromRaw = (raw) =>
  createPublicKey({ format: 'jwk', key: { kty: 'OKP', crv: 'Ed25519', x: b64uEncode(raw) } });

const ED25519_PKCS8_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex');
const ed25519PublicFromSeed = (seed) =>
  createPublicKey(createPrivateKey({
    format: 'der', type: 'pkcs8', key: Buffer.concat([ED25519_PKCS8_PREFIX, seed]),
  }));

// Ed25519 signs its message directly (RFC 8032, no pre-hash). The JCS profile's
// message is the 32-byte SHA-256 digest of the canonical bytes; the JOSE profile's
// is the ASCII `header.payload`. Both are just "a message" to this call.
const ed25519Verify = (pubKey, message, sig) => cryptoVerify(null, message, pubKey, sig);

// P-256 scalar multiplication, so `kat-keypair-005-p256`'s pinned public point is
// actually derived rather than assumed. Node exposes no scalar-mult primitive and
// this is the only way to check the vector end-to-end instead of skipping it.
const P = 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffffn;
const A = P - 3n;
const B = 0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604bn;
const GX = 0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296n;
const GY = 0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5n;

const mod = (x) => ((x % P) + P) % P;
function powMod(base, exp) {
  let r = 1n, b = mod(base), e = exp;
  while (e > 0n) { if (e & 1n) r = (r * b) % P; b = (b * b) % P; e >>= 1n; }
  return r;
}
function ecAdd(p1, p2) {
  if (p1 === null) return p2;
  if (p2 === null) return p1;
  const [x1, y1] = p1, [x2, y2] = p2;
  if (x1 === x2 && mod(y1 + y2) === 0n) return null;
  const lam = x1 === x2 && y1 === y2
    ? mod((3n * x1 * x1 + A) * powMod(2n * y1, P - 2n))
    : mod((y2 - y1) * powMod(x2 - x1, P - 2n));
  const x3 = mod(lam * lam - x1 - x2);
  return [x3, mod(lam * (x1 - x3) - y1)];
}
function ecMul(k, point) {
  let result = null, addend = point, n = k;
  while (n > 0n) { if (n & 1n) result = ecAdd(result, addend); addend = ecAdd(addend, addend); n >>= 1n; }
  return result;
}
const onCurve = ([x, y]) => mod(y * y) === mod(x * x * x + A * x + B);
const compress = ([x, y]) =>
  Buffer.concat([Buffer.from([y % 2n === 0n ? 0x02 : 0x03]), Buffer.from(x.toString(16).padStart(64, '0'), 'hex')]);

// ── the signing-input rule ───────────────────────────────────────────────────
//
// The three wrapped JCS-profile artifacts are transported inside a JSON object
// whose key names the artifact (RFC-AITP-0001 §5.4.1). That key is transport
// routing metadata and is never signed. Each vector declares which of the two
// its pinned bytes are, and this table is what the declaration is checked
// against — a vector cannot certify its own convention.

const ARTIFACT_WRAPPERS = new Set(['manifest', 'revocation_list', 'session_bundle']);

// The three JCS-profile artifact vectors. For these the answer is not a matter of
// declaration: RFC-AITP-0001 §5.4.1 requires the inner artifact body, so anything
// else is non-conformant however the vector describes itself.
const JCS_ARTIFACT_VECTORS = new Set(['kat-manifest-001', 'kat-revocation-001', 'kat-session-bundle-001']);

function declaredSigningInput(vector) {
  const decl = vector.signing_input;
  if (decl === undefined) {
    throw new Error(
      `vector has an "object" but no "signing_input" declaration. Every vector ` +
      `carrying pinned canonical bytes MUST state whether those bytes are the ` +
      `inner artifact body ("body") or the transport envelope ("envelope").`);
  }
  if (decl !== 'body' && decl !== 'envelope') {
    throw new Error(`signing_input must be "body" or "envelope", got ${JSON.stringify(decl)}`);
  }
  if (decl === 'envelope' && JCS_ARTIFACT_VECTORS.has(vector.id)) {
    throw new Error(
      `signing_input is "envelope", but this is a JCS-profile artifact whose signing ` +
      `input is the inner body (RFC-AITP-0001 §5.4.1, RFC-AITP-0003 §6.1, ` +
      `RFC-AITP-0008 §1.5, RFC-AITP-0010 §3). Pinning the transport wrapper is the ` +
      `defect corrected in the v0.2 signing-input change (see CHANGELOG.md); it must ` +
      `not be reintroduced. If the wrapper ` +
      `really must be pinned, that is an RFC change, not a vector change.`);
  }
  return decl;
}

// Returns { signed, alternative, wrapperKey } for a vector's `object`.
function shapes(vector) {
  const obj = vector.object;
  // A wrapper key counts wherever it appears, not only in first position: the
  // wire revocation envelope is {"revocation_list": …, "signature": …} and JSON
  // member order is not significant, so a pasted-in envelope must be caught
  // regardless of which member happens to come first. No inner artifact body
  // has a member named after an artifact, so this cannot false-positive.
  const wrapperKey = Object.keys(obj).find((k) => ARTIFACT_WRAPPERS.has(k)) ?? null;
  const decl = declaredSigningInput(vector);

  if (decl === 'envelope') {
    if (!wrapperKey) throw new Error(`signing_input "envelope" but object has no artifact wrapper key`);
    return { signed: obj, alternative: obj[wrapperKey], wrapperKey };
  }
  // "body": the object IS the inner artifact body; the alternative is it wrapped.
  if (wrapperKey) {
    throw new Error(
      `signing_input "body" but the object is still wrapped in "${wrapperKey}". ` +
      `The pinned bytes must be the inner artifact body — see RFC-AITP-0001 §5.4.1.`);
  }
  const inferred = inferWrapperKey(vector.id);
  return { signed: obj, alternative: inferred ? { [inferred]: obj } : null, wrapperKey: inferred };
}

function inferWrapperKey(vectorId) {
  if (vectorId.includes('manifest')) return 'manifest';
  if (vectorId.includes('revocation')) return 'revocation_list';
  if (vectorId.includes('session-bundle')) return 'session_bundle';
  return null;
}

// ── checks ───────────────────────────────────────────────────────────────────

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

function checkKeypairs() {
  console.log('── keypairs.json: seed → public key → AID ──');
  const { vectors } = readJson(join(KAT, 'keypairs.json'));
  const byId = new Map(vectors.map((v) => [v.id, v]));
  assertContents('keypairs.json', byId, KEYPAIRS_EXPECTED);
  for (const v of vectors) {
    if (v.algorithm === 'p256') {
      check(`${v.id} scalar → SEC1 compressed point → AID`, () => {
        const d = BigInt('0x' + v.private_scalar_hex);
        const point = ecMul(d, [GX, GY]);
        if (!point) throw new Error('scalar multiplication produced the point at infinity');
        if (!onCurve(point)) throw new Error('derived point is not on P-256');
        const comp = compress(point);
        eq(comp.toString('hex'), v.pubkey_compressed_hex, 'compressed point');
        eq(b64uEncode(comp), v.pubkey_b64url, 'pubkey_b64url');
        eq(v.aid, `aid:pubkey:p256:${v.pubkey_b64url}`, 'aid');
      });
    } else {
      check(`${v.id} seed → Ed25519 public key → AID`, () => {
        const seed = Buffer.from(v.seed_hex, 'hex');
        if (seed.length !== 32) throw new Error(`seed is ${seed.length} bytes, expected 32`);
        const jwk = ed25519PublicFromSeed(seed).export({ format: 'jwk' });
        eq(jwk.x, v.pubkey_b64url, 'pubkey_b64url');
        eq(v.aid, `aid:pubkey:${v.pubkey_b64url}`, 'aid');
      });
    }
  }
  return byId;
}

function checkThumbprints(keypairs) {
  console.log('── jwk-thumbprints.json: RFC 7638 ──');
  const { vectors } = readJson(join(KAT, 'jwk-thumbprints.json'));
  assertContents('jwk-thumbprints.json', new Map(vectors.map((v) => [v.id, v])), THUMBPRINTS_EXPECTED);
  for (const v of vectors) {
    check(`${v.id} canonical JWK → SHA-256 → jkt`, () => {
      const jwk = JSON.parse(v.jwk_canonical);
      const canonical = jcs(jwk);
      eq(canonical, v.jwk_canonical, 'canonical JWK is not in RFC 7638 lex-ordered form');
      eq(utf8(canonical).toString('hex'), v.jwk_canonical_hex, 'jwk_canonical_hex');
      const digest = sha256(utf8(canonical));
      eq(digest.toString('hex'), v.sha256_hex, 'sha256_hex');
      eq(b64uEncode(digest), v.jkt, 'jkt');
      // The JWK must describe the keypair it claims to. For EC the JWK carries the
      // affine coordinates while keypairs.json pins the SEC1 compressed point, so
      // recompose before comparing rather than comparing different encodings.
      const kp = keypairs.get(v.keypair_ref);
      if (!kp) throw new Error(`keypair_ref ${v.keypair_ref} not in keypairs.json`);
      if (jwk.kty === 'EC') {
        const x = BigInt('0x' + b64uDecode(jwk.x, 32, 'jwk.x').toString('hex'));
        const y = BigInt('0x' + b64uDecode(jwk.y, 32, 'jwk.y').toString('hex'));
        if (!onCurve([x, y])) throw new Error('JWK coordinates are not a point on P-256');
        eq(b64uEncode(compress([x, y])), kp.pubkey_b64url, `JWK point does not match ${v.keypair_ref}`);
      } else {
        eq(jwk.x, kp.pubkey_b64url, `jwk x does not match ${v.keypair_ref}`);
      }
    });
  }
}

// Every vector this script knows how to check, and the members each MUST carry.
// A vector missing from the file, or a member missing from a vector, is a failure
// — not a quietly reduced check count. Adding a vector to jcs-sha256.json without
// adding it here is also a failure (see the `recognized` check below), so the file
// and this manifest cannot drift apart in either direction.
const JCS_EXPECTED = new Map([
  ['kat-manifest-001', ['object', 'signing_input', 'jcs_canonical_hex', 'jcs_canonical_len_bytes', 'sha256_hex', 'sha256_b64url']],
  ['kat-revocation-001', ['object', 'signing_input', 'jcs_canonical_hex', 'jcs_canonical_len_bytes', 'sha256_hex', 'sha256_b64url']],
  ['kat-session-bundle-001', ['object', 'signing_input', 'jcs_canonical_hex', 'jcs_canonical_len_bytes', 'sha256_hex', 'sha256_b64url', 'coordinator_signature_b64url']],
  ['kat-manifest-pop-001', ['challenge', 'decoded_hex', 'sha256_hex', 'sha256_b64url', 'signing_keypair_id', 'signer_aid', 'signature_b64url']],
  ['kat-pinned-key-proof-001', ['sender_aid', 'receiver_aid', 'message_id', 'timestamp', 'pop_nonce', 'proof_input_hex', 'proof_input_len_bytes', 'sha256_hex', 'sha256_b64url', 'signing_keypair_id', 'signer_aid', 'signature_b64url']],
  ['kat-multihop-chain-001', ['voucher_jws', 'chain', 'chain_entry_sha256_b64url', 'digest_array_jcs', 'chain_hash', 'outer_delegation_jws']],
  ['kat-multihop-truncation-001', ['chain_hash_full', 'chain_truncated', 'chain_hash_truncated', 'must_differ']],
]);

const KEYPAIRS_EXPECTED = new Map([
  ['kat-keypair-001', ['seed_hex', 'pubkey_b64url', 'aid']],
  ['kat-keypair-002', ['seed_hex', 'pubkey_b64url', 'aid']],
  ['kat-keypair-003', ['seed_hex', 'pubkey_b64url', 'aid']],
  ['kat-keypair-004', ['seed_hex', 'pubkey_b64url', 'aid']],
  ['kat-keypair-005-p256', ['private_scalar_hex', 'pubkey_compressed_hex', 'pubkey_b64url', 'aid']],
  ['kat-keypair-006-attacker', ['seed_hex', 'pubkey_b64url', 'aid']],
]);

const THUMBPRINTS_EXPECTED = new Map([
  ['kat-jwk-thumb-001', ['keypair_ref', 'jwk_canonical', 'jwk_canonical_hex', 'sha256_hex', 'jkt']],
  ['kat-jwk-thumb-002', ['keypair_ref', 'jwk_canonical', 'jwk_canonical_hex', 'sha256_hex', 'jkt']],
  ['kat-jwk-thumb-003', ['keypair_ref', 'jwk_canonical', 'jwk_canonical_hex', 'sha256_hex', 'jkt']],
  ['kat-jwk-thumb-004', ['keypair_ref', 'jwk_canonical', 'jwk_canonical_hex', 'sha256_hex', 'jkt']],
  ['kat-jwk-thumb-005-p256', ['keypair_ref', 'jwk_canonical', 'jwk_canonical_hex', 'sha256_hex', 'jkt']],
]);

// What each pinned member must *be*. Asserting the required type is strictly
// stronger than enumerating forbidden values: several consuming checks are gated on
// truthiness, so any falsy value — `null`, `""`, `[]`, `false`, `0` — would read as
// absent to them and silently remove coverage. Enumerating bad values leaves
// whichever falsy value the list forgot; requiring a type leaves none.
const nonEmptyString = (x) => typeof x === 'string' && x.trim().length > 0;
const MEMBER_TYPES = new Map([
  ['object', { ok: (x) => x !== null && typeof x === 'object' && !Array.isArray(x), want: 'a JSON object' }],
  ['jcs_canonical_len_bytes', { ok: (x) => Number.isInteger(x) && x > 0, want: 'a positive integer' }],
  ['proof_input_len_bytes', { ok: (x) => Number.isInteger(x) && x > 0, want: 'a positive integer' }],
  ['timestamp', { ok: (x) => Number.isInteger(x) && x > 0, want: 'a positive integer' }],
  ['must_differ', { ok: (x) => x === true, want: 'exactly true' }],
  ['chain', { ok: (x) => Array.isArray(x) && x.length > 0 && x.every(nonEmptyString), want: 'a non-empty array of strings' }],
  ['chain_entry_sha256_b64url', { ok: (x) => Array.isArray(x) && x.length > 0 && x.every(nonEmptyString), want: 'a non-empty array of strings' }],
  // Legitimately empty — an emptied chain is exactly what this vector pins.
  ['chain_truncated', { ok: (x) => Array.isArray(x) && x.every(nonEmptyString), want: 'an array of strings' }],
]);
const DEFAULT_MEMBER_TYPE = { ok: nonEmptyString, want: 'a non-empty string' };

function assertContents(fileLabel, byId, expected) {
  for (const [id, members] of expected) {
    check(`${fileLabel} contains ${id} with every pinned member`, () => {
      const v = byId.get(id);
      if (!v) throw new Error(`vector is MISSING from ${fileLabel}. A pinned vector may not be deleted to silence a check.`);
      const absent = members.filter((m) => v[m] === undefined);
      if (absent.length > 0) {
        throw new Error(`missing pinned member(s): ${absent.join(', ')}. Deleting a pinned member is not a way to make this script pass.`);
      }
      const badTypes = members
        .map((m) => [m, MEMBER_TYPES.get(m) ?? DEFAULT_MEMBER_TYPE])
        .filter(([m, spec]) => !spec.ok(v[m]))
        .map(([m, spec]) => `${m} (must be ${spec.want}, got ${JSON.stringify(v[m])})`);
      if (badTypes.length > 0) {
        throw new Error(
          `pinned member(s) present but unusable: ${badTypes.join('; ')}. ` +
          `Neutering a pinned member is not a way to make this script pass.`);
      }
    });
  }
}

function checkJcsVectors(keypairs) {
  console.log('── jcs-sha256.json: canonical bytes, digests, pinned signatures ──');
  const { vectors } = readJson(join(KAT, 'jcs-sha256.json'));
  const byId = new Map(vectors.map((v) => [v.id, v]));

  // Presence is asserted before anything is checked. Without this the guard is
  // hollowable: deleting a vector, or deleting one pinned member from a vector,
  // would simply remove the checks that cover it and the script would exit 0.
  // That is the same failure mode as a harness that adapts to its input.
  assertContents('jcs-sha256.json', byId, JCS_EXPECTED);

  for (const v of vectors) {
    // An unrecognized vector shape is a failure, never a silent skip — a guard
    // that quietly ignores what it does not understand rots exactly the way the
    // signed-example coverage gap did.
    if (!JCS_EXPECTED.has(v.id)) {
      check(`${v.id} recognized`, () => {
        throw new Error(`unknown vector id — add it to JCS_EXPECTED with its required members, or this vector is unguarded`);
      });
      continue;
    }

    if (v.object) {
      let shape;
      check(`${v.id} declares a valid signing_input`, () => { shape = shapes(v); });
      if (!shape) continue;
      const { signed, alternative, wrapperKey } = shape;

      check(`${v.id} canonical bytes + digest (signing_input: ${v.signing_input})`, () => {
        const canonical = jcs(signed);
        const bytes = utf8(canonical);
        eq(bytes.toString('hex'), v.jcs_canonical_hex, 'jcs_canonical_hex');
        eq(bytes.length, v.jcs_canonical_len_bytes, 'jcs_canonical_len_bytes');
        const digest = sha256(bytes);
        eq(digest.toString('hex'), v.sha256_hex, 'sha256_hex');
        eq(b64uEncode(digest), v.sha256_b64url, 'sha256_b64url');
      });

      if (v.coordinator_signature_b64url) {
        const coordAid = signed.coordinator ?? signed.session_bundle?.coordinator;
        check(`${v.id} coordinator signature verifies over the declared signing input`, () => {
          const pub = ed25519PublicFromRaw(aidRawKey(coordAid));
          const sig = b64uDecode(v.coordinator_signature_b64url, 64, 'coordinator_signature_b64url');
          if (!ed25519Verify(pub, sha256(utf8(jcs(signed))), sig)) {
            throw new Error(`signature does not verify over the ${v.signing_input} form`);
          }
        });
        check(`${v.id} coordinator signature does NOT verify over the other shape`, () => {
          if (!alternative) throw new Error('no alternative shape to test against');
          const pub = ed25519PublicFromRaw(aidRawKey(coordAid));
          const sig = b64uDecode(v.coordinator_signature_b64url, 64, 'coordinator_signature_b64url');
          if (ed25519Verify(pub, sha256(utf8(jcs(alternative))), sig)) {
            throw new Error(
              `signature verifies over BOTH shapes — the wrapper "${wrapperKey}" is not ` +
              `distinguishing the signing input, so this vector pins nothing`);
          }
        });
      }
    }

    if (v.id === 'kat-manifest-pop-001') {
      check(`${v.id} PoP signing input + signature`, () => {
        const decoded = b64uDecode(v.challenge, 16, 'challenge');
        eq(decoded.toString('hex'), v.decoded_hex, 'decoded_hex');
        const digest = sha256(decoded);
        eq(digest.toString('hex'), v.sha256_hex, 'sha256_hex');
        eq(b64uEncode(digest), v.sha256_b64url, 'sha256_b64url');
        const kp = keypairs.get(v.signing_keypair_id);
        if (!kp) throw new Error(`signing_keypair_id ${v.signing_keypair_id} is not in keypairs.json`);
        eq(v.signer_aid, kp.aid, `signer_aid does not match ${v.signing_keypair_id}`);
        const pub = ed25519PublicFromRaw(aidRawKey(v.signer_aid));
        const sig = b64uDecode(v.signature_b64url, 64, 'signature_b64url');
        if (!ed25519Verify(pub, digest, sig)) throw new Error('PoP signature does not verify');
      });
      check(`${v.id} PoP signature does NOT verify over the ASCII challenge`, () => {
        // The single most common interop bug per RFC-AITP-0001 §5.4.2 — pin that
        // the pinned signature actually distinguishes decoded bytes from ASCII.
        const pub = ed25519PublicFromRaw(aidRawKey(v.signer_aid));
        const sig = b64uDecode(v.signature_b64url, 64, 'signature_b64url');
        if (ed25519Verify(pub, sha256(utf8(v.challenge)), sig)) {
          throw new Error('signature verifies over the ASCII form too — the vector proves nothing');
        }
      });
    }

    if (v.id === 'kat-pinned-key-proof-001') {
      // RFC-AITP-0002 §3.1 pinned-key proof input. Fixes issue #17 erratum 1: the
      // prose once called the timestamp field `timestamp_be_8_bytes` (an 8-byte
      // big-endian signed 64-bit integer), but the only concrete pinned proof in
      // the conformance pack (id-007) only verifies when the timestamp is instead
      // its base-10 ASCII decimal string. This vector reuses id-007's real tuple
      // and signature verbatim, so both the positive and negative encoding checks
      // below are load-bearing, not merely descriptive.
      const buildProofInput = (tsBytes) => Buffer.concat([
        utf8('aitp-pinned-key-v1\0'),
        utf8(v.sender_aid), utf8('\0'),
        utf8(v.receiver_aid), utf8('\0'),
        utf8(v.message_id), utf8('\0'),
        tsBytes, utf8('\0'),
        b64uDecode(v.pop_nonce, 16, 'pop_nonce'),
      ]);
      check(`${v.id} proof_input (ASCII-decimal timestamp) + digest + signature`, () => {
        const asciiInput = buildProofInput(utf8(String(v.timestamp)));
        eq(asciiInput.toString('hex'), v.proof_input_hex, 'proof_input_hex');
        eq(asciiInput.length, v.proof_input_len_bytes, 'proof_input_len_bytes');
        const digest = sha256(asciiInput);
        eq(digest.toString('hex'), v.sha256_hex, 'sha256_hex');
        eq(b64uEncode(digest), v.sha256_b64url, 'sha256_b64url');
        const kp = keypairs.get(v.signing_keypair_id);
        if (!kp) throw new Error(`signing_keypair_id ${v.signing_keypair_id} is not in keypairs.json`);
        eq(v.signer_aid, kp.aid, `signer_aid does not match ${v.signing_keypair_id}`);
        const pub = ed25519PublicFromRaw(aidRawKey(v.signer_aid));
        const sig = b64uDecode(v.signature_b64url, 64, 'signature_b64url');
        if (!ed25519Verify(pub, digest, sig)) throw new Error('proof signature does not verify over the ASCII-decimal proof_input');
      });
      check(`${v.id} proof signature does NOT verify over an 8-byte big-endian timestamp`, () => {
        // The exact prose-vs-vector defect issue #17 reports: an implementer
        // following the old "big-endian signed 64-bit integer" prose would fail
        // this pinned vector. Pin that the vector actually distinguishes the two
        // encodings, not just that ASCII happens to verify.
        const beBytes = Buffer.alloc(8);
        beBytes.writeBigInt64BE(BigInt(v.timestamp));
        const beInput = buildProofInput(beBytes);
        const pub = ed25519PublicFromRaw(aidRawKey(v.signer_aid));
        const sig = b64uDecode(v.signature_b64url, 64, 'signature_b64url');
        if (ed25519Verify(pub, sha256(beInput), sig)) {
          throw new Error('signature verifies over the big-endian form too — the vector proves nothing');
        }
      });
    }

    if (v.id === 'kat-multihop-chain-001') {
      check(`${v.id} digest-array chain_hash`, () => {
        const digests = v.chain.map((entry) => b64uEncode(sha256(utf8(entry))));
        if (JSON.stringify(digests) !== JSON.stringify(v.chain_entry_sha256_b64url)) {
          throw new Error(`per-entry digests mismatch\n         got      ${JSON.stringify(digests)}\n         expected ${JSON.stringify(v.chain_entry_sha256_b64url)}`);
        }
        const arrayJcs = jcs(digests);
        eq(arrayJcs, v.digest_array_jcs, 'digest_array_jcs');
        eq(b64uEncode(sha256(utf8(arrayJcs))), v.chain_hash, 'chain_hash');
      });
      check(`${v.id} embedded JWS tokens verify`, () => {
        verifyCompactJws(v.voucher_jws, 'aitp-grant+jwt');
        verifyCompactJws(v.outer_delegation_jws, 'aitp-delegation+jwt');
        for (const entry of v.chain) verifyCompactJws(entry, 'aitp-delegation+jwt');
      });
    }

    if (v.id === 'kat-multihop-truncation-001') {
      check(`${v.id} truncated chain_hash differs`, () => {
        const digests = v.chain_truncated.map((e) => b64uEncode(sha256(utf8(e))));
        eq(b64uEncode(sha256(utf8(jcs(digests)))), v.chain_hash_truncated, 'chain_hash_truncated');
        if (v.chain_hash_truncated === v.chain_hash_full) {
          throw new Error('truncated and full chain_hash are equal — the vector asserts nothing');
        }
        if (v.must_differ !== true) throw new Error('must_differ is not true');
      });
      check(`${v.id} chain_hash_full agrees with kat-multihop-chain-001`, () => {
        // Otherwise chain_hash_full is pinned but only ever used in an inequality,
        // so it could hold any value at all and this vector would still pass.
        const chain = byId.get('kat-multihop-chain-001');
        if (!chain) throw new Error('kat-multihop-chain-001 is missing');
        eq(v.chain_hash_full, chain.chain_hash, 'chain_hash_full');
      });
    }
  }
}

// AID → raw 32-byte Ed25519 public key. Accepts the untagged v0.1-style
// `aid:pubkey:<b64url>` and the v0.2 algorithm-tagged `aid:pubkey:ed25519:<b64url>`.
function aidRawKey(aid) {
  if (typeof aid !== 'string' || !aid.startsWith('aid:pubkey:')) {
    throw new Error(`not an aid:pubkey: identifier: ${JSON.stringify(aid)}`);
  }
  let rest = aid.slice('aid:pubkey:'.length);
  if (rest.startsWith('ed25519:')) rest = rest.slice('ed25519:'.length);
  if (rest.startsWith('p256:')) throw new Error(`P-256 AID passed where Ed25519 was expected: ${aid}`);
  return b64uDecode(rest, 32, `public key in ${aid}`);
}

function verifyCompactJws(token, expectedTyp) {
  const parts = token.split('.');
  if (parts.length !== 3) throw new Error(`compact JWS must have 3 segments, got ${parts.length}`);
  const [h, p, s] = parts;
  const header = JSON.parse(Buffer.from(h, 'base64url').toString('utf8'));
  if (header.typ !== expectedTyp) throw new Error(`typ is ${header.typ}, expected ${expectedTyp}`);
  if (header.alg !== 'EdDSA') throw new Error(`alg is ${header.alg}, expected EdDSA`);
  const claims = JSON.parse(Buffer.from(p, 'base64url').toString('utf8'));
  const pub = ed25519PublicFromRaw(aidRawKey(claims.iss));
  const sig = b64uDecode(s, 64, 'JWS signature segment');
  if (!ed25519Verify(pub, utf8(`${h}.${p}`), sig)) {
    throw new Error(`signature does not verify under iss ${claims.iss}`);
  }
  return claims;
}

function checkSignedExamples() {
  console.log('── signed-examples/: committed signatures, verified as committed ──');

  // JCS-profile artifacts. These are the two the conformance suite never
  // executed cross-implementation, which is how a wrapped revocation signature
  // shipped. Both the positive and the negative assertion matter: the negative
  // is what makes a silent re-wrap impossible.
  const jcsArtifacts = [
    { rel: 'manifest/kat-keypair-001-manifest.json', wrapper: 'manifest', sigInsideBody: true, issuerField: 'aid' },
    { rel: 'revocation/kat-keypair-001-snapshot.json', wrapper: 'revocation_list', sigInsideBody: false, issuerField: 'issuer' },
    // The session bundle is the artifact whose signature placement was wrong in
    // the schema through a full release (fixed by PR #30): the signature is a
    // member of the `session_bundle` body, not a sibling of the wrapper (RFC-AITP-0001
    // §5.4.1, RFC-AITP-0010 §3). This is the check that would have caught it.
    { rel: 'session-bundle/kat-keypair-001-bundle.json', wrapper: 'session_bundle', sigInsideBody: true, issuerField: 'coordinator' },
  ];

  for (const art of jcsArtifacts) {
    const path = join(SIGNED, art.rel);
    check(`${art.rel} exists`, () => {
      if (!existsSync(path)) throw new Error('file is missing');
    });
    if (!existsSync(path)) continue;
    const file = readJson(path);
    const wrapped = file[art.wrapper];
    if (wrapped === undefined) {
      check(`${art.rel} shape`, () => { throw new Error(`no "${art.wrapper}" member`); });
      continue;
    }

    // The signing input, per RFC-AITP-0001 §5.4.1: the inner artifact body,
    // carrying no signature of its own. For the manifest the signature is a
    // member of the body and is removed; for the revocation snapshot it is a
    // sibling of the body and there is nothing to remove.
    let body, sigStr, issuerAid;
    if (art.sigInsideBody) {
      sigStr = wrapped.signature;
      body = Object.fromEntries(Object.entries(wrapped).filter(([k]) => k !== 'signature'));
      issuerAid = wrapped[art.issuerField];
    } else {
      sigStr = file.signature;
      body = wrapped;
      issuerAid = wrapped[art.issuerField];
      check(`${art.rel} inner body carries no signature member`, () => {
        if ('signature' in body) {
          throw new Error('the revocation body must not contain a signature member; it is a sibling of the wrapper');
        }
      });
    }

    check(`${art.rel} signature verifies over the INNER body`, () => {
      const pub = ed25519PublicFromRaw(aidRawKey(issuerAid));
      const sig = b64uDecode(sigStr, 64, 'signature');
      if (!ed25519Verify(pub, sha256(utf8(jcs(body))), sig)) {
        throw new Error(
          `signature does not verify over the inner body. If it verifies over ` +
          `{"${art.wrapper}": …} instead, this artifact signs the transport wrapper, ` +
          `which RFC-AITP-0001 §5.4.1 forbids.`);
      }
    });

    check(`${art.rel} signature does NOT verify over the WRAPPED form`, () => {
      const pub = ed25519PublicFromRaw(aidRawKey(issuerAid));
      const sig = b64uDecode(sigStr, 64, 'signature');
      if (ed25519Verify(pub, sha256(utf8(jcs({ [art.wrapper]: body }))), sig)) {
        throw new Error('signature verifies over the wrapper too — the artifact pins no convention');
      }
    });

    // The session bundle's standalone signed example must be the SAME artifact
    // as the pinned kat-session-bundle-001 vector in jcs-sha256.json, not a
    // freshly-minted lookalike. Its 922-byte canonical form and
    // c577854d… digest are load-bearing (referenced by CHANGELOG as a
    // migration record); this check pins the new file to those existing
    // values rather than letting it drift into a second, unpinned artifact.
    if (art.rel === 'session-bundle/kat-keypair-001-bundle.json') {
      check(`${art.rel} body agrees with pinned kat-session-bundle-001 (jcs-sha256.json)`, () => {
        const { vectors } = readJson(join(KAT, 'jcs-sha256.json'));
        const vector = vectors.find((v) => v.id === 'kat-session-bundle-001');
        if (!vector) throw new Error('kat-session-bundle-001 is missing from jcs-sha256.json');
        const bytes = utf8(jcs(body));
        eq(bytes.toString('hex'), vector.jcs_canonical_hex, 'jcs_canonical_hex');
        eq(bytes.length, vector.jcs_canonical_len_bytes, 'jcs_canonical_len_bytes');
        eq(sha256(bytes).toString('hex'), vector.sha256_hex, 'sha256_hex');
        eq(sigStr, vector.coordinator_signature_b64url, 'coordinator_signature_b64url');
      });
    }
  }

  // Compact-JWS artifacts.
  // The token member is NAMED, never discovered. Selecting it with a
  // `.find(k => k.endsWith('_token'))` would let an added `aaa_token` member
  // holding a valid copy shadow the real pinned token, which could then be
  // corrupted unnoticed. Discovering structure instead of asserting it is the
  // exact defect this script exists to catch.
  const jwsArtifacts = [
    { rel: 'tct/kat-keypair-001-issues-002.json', typ: 'aitp-tct+jwt', tokenMember: 'tct_token' },
    { rel: 'grant-voucher/kat-voucher-001.json', typ: 'aitp-grant+jwt', tokenMember: 'voucher_token' },
    { rel: 'delegation/single-hop-001-002-003.json', typ: 'aitp-delegation+jwt', tokenMember: 'delegation_token' },
  ];
  for (const art of jwsArtifacts) {
    const path = join(SIGNED, art.rel);
    check(`${art.rel} compact JWS verifies and matches decoded_claims`, () => {
      if (!existsSync(path)) throw new Error('file is missing');
      const file = readJson(path);
      const token = file[art.tokenMember];
      if (!nonEmptyString(token)) {
        throw new Error(`"${art.tokenMember}" must be a non-empty string, got ${JSON.stringify(token)}`);
      }
      const strays = Object.keys(file).filter((k) => k.endsWith('_token') && k !== art.tokenMember);
      if (strays.length > 0) {
        throw new Error(
          `unexpected *_token member(s): ${strays.join(', ')}. This file pins exactly one ` +
          `token, "${art.tokenMember}"; a second one can only shadow it.`);
      }
      const claims = verifyCompactJws(token, art.typ);
      eq(jcs(claims), jcs(file.decoded_claims), 'decoded_claims does not match the token payload');
    });
  }
}

