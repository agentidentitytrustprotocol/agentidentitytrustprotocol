const ed25519PublicFromRaw = (raw) =>
  createPublicKey({ format: 'jwk', key: { kty: 'OKP', crv: 'Ed25519', x: b64uEncode(raw) } });

const ED25519_PKCS8_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex');
const ed25519PublicFromSeed = (seed) =>
  createPublicKey(createPrivateKey({
    format: 'der', type: 'pkcs8', key: Buffer.concat([ED25519_PKCS8_PREFIX, seed]),
  }));

// ── Ed25519 in BigInt (RFC 8032 §5.1) ────────────────────────────────────────
//
// Enough of the curve to apply RFC-AITP-0001 §5.4.7 without trusting OpenSSL:
// point decoding with and without the canonical-encoding checks, scalar
// multiplication for the small-order test and both verification equations.
// Extended twisted-Edwards coordinates [X, Y, Z, T], as in RFC 8032 §5.1.4.

const EP = 2n ** 255n - 19n;
const EL = 2n ** 252n + 27742317777372353535851937790883648493n;
const emod = (x) => ((x % EP) + EP) % EP;
function epow(base, exp) {
  let r = 1n, b = emod(base), e = exp;
  while (e > 0n) { if (e & 1n) r = (r * b) % EP; b = (b * b) % EP; e >>= 1n; }
  return r;
}
const ED = emod(-121665n * epow(121666n, EP - 2n));
const SQRT_M1 = epow(2n, (EP - 1n) / 4n);
const E_IDENTITY = [0n, 1n, 1n, 0n];

function edAdd(p1, p2) {
  const a = emod((p1[1] - p1[0]) * (p2[1] - p2[0]));
  const b = emod((p1[1] + p1[0]) * (p2[1] + p2[0]));
  const c = emod(2n * p1[3] * p2[3] * ED);
  const d = emod(2n * p1[2] * p2[2]);
  const e = b - a, f = d - c, g = d + c, h = b + a;
  return [emod(e * f), emod(g * h), emod(f * g), emod(e * h)];
}
function edMul(k, point) {
  let result = E_IDENTITY, addend = point, n = k;
  while (n > 0n) { if (n & 1n) result = edAdd(result, addend); addend = edAdd(addend, addend); n >>= 1n; }
  return result;
}
const edEqual = (p1, p2) =>
  emod(p1[0] * p2[2] - p2[0] * p1[2]) === 0n && emod(p1[1] * p2[2] - p2[1] * p1[2]) === 0n;
const leToBig = (buf) => BigInt('0x' + (Buffer.from(buf).reverse().toString('hex') || '0'));
const bigToLe32 = (x) => Buffer.from(x.toString(16).padStart(64, '0'), 'hex').reverse();

// RFC 8032 §5.1.3. `strict` rejects the two non-canonical encodings the RFC
// allows a lax decoder to accept: y >= p, and x = 0 with the sign bit set
// ("negative zero"). Those are exactly how the small-order points acquire their
// extra, non-canonical encodings, so a strict decoder sees each point once.
function edDecode(buf, strict) {
  if (buf.length !== 32) return null;
  const n = leToBig(buf);
  const sign = n >> 255n;
  let y = n & ((1n << 255n) - 1n);
  if (y >= EP) { if (strict) return null; y %= EP; }
  const u = emod(y * y - 1n), v = emod(ED * y * y + 1n);
  let x = emod(u * epow(v, 3n) * epow(u * epow(v, 7n), (EP - 5n) / 8n));
  const vx2 = emod(v * x * x);
  if (vx2 !== u) {
    if (vx2 !== emod(-u)) return null; // not on the curve
    x = emod(x * SQRT_M1);
  }
  if (x === 0n && sign === 1n && strict) return null;
  if ((x & 1n) !== sign) x = emod(-x);
  return [x, y, 1n, emod(x * y)];
}
const E_BASE = edDecode(bigToLe32(emod(4n * epow(5n, EP - 2n))), true);
const edIsSmallOrder = (point) => edEqual(edMul(8n, point), E_IDENTITY);
const edChallenge = (rBytes, aBytes, message) =>
  leToBig(createHash('sha512').update(rBytes).update(aBytes).update(message).digest()) % EL;

// Why a §5.4.7 verifier rejects this (pub, sig) before any equation is
// evaluated, or null if it does not.
function ed25519StrictReason(pubRaw, sig) {
  if (pubRaw.length !== 32) return 'public key is not 32 bytes';
  if (sig.length !== 64) return 'signature is not 64 bytes';
  if (leToBig(sig.subarray(32)) >= EL) return 'S >= L (non-canonical S)';
  const a = edDecode(pubRaw, true);
  if (!a) return 'public key is not a canonical point encoding';
  if (edIsSmallOrder(a)) return 'public key has small order';
  if (!edDecode(sig.subarray(0, 32), true)) return 'R is not a canonical point encoding';
  return null;
}

// The lax profile a §5.4.7 verifier must NOT implement: permissive decoding,
// S reduced mod L, small-order keys allowed, cofactored equation
// [8][S]B = [8]R + [8][k]A. Used only to prove a negative vector is meaningful,
// i.e. that it is something a lax verifier really would accept.
function ed25519VerifyLax(pubRaw, message, sig) {
  const a = edDecode(pubRaw, false), r = edDecode(sig.subarray(0, 32), false);
  if (!a || !r) return false;
  const s = leToBig(sig.subarray(32)) % EL;
  const k = edChallenge(sig.subarray(0, 32), pubRaw, message);
  return edEqual(edMul(8n, edMul(s, E_BASE)), edMul(8n, edAdd(r, edMul(k, a))));
}

// Strict Ed25519 (RFC-AITP-0001 §5.4.7). Ed25519 signs its message directly
// (RFC 8032, no pre-hash). The JCS profile's message is the 32-byte digest
// d = sha256(signing input) (§5.4.6); the JOSE profile's is the ASCII
// `header.payload`. Both are just "a message" here.
function ed25519Verify(pubRaw, message, sig) {
  if (ed25519StrictReason(pubRaw, sig) !== null) return false;
  const a = edDecode(pubRaw, true), r = edDecode(sig.subarray(0, 32), true);
  const k = edChallenge(sig.subarray(0, 32), pubRaw, message);
  const bigOk = edEqual(edMul(leToBig(sig.subarray(32)), E_BASE), edAdd(r, edMul(k, a)));
  const nodeOk = cryptoVerify(null, message, ed25519PublicFromRaw(pubRaw), sig);
  if (bigOk !== nodeOk) {
    throw new Error(`Ed25519 implementations disagree: BigInt cofactorless equation says ${bigOk}, crypto.verify says ${nodeOk}`);
  }
  return bigOk;
}

// P-256 scalar multiplication, so `kat-keypair-005-p256`'s pinned public point is
// actually derived rather than assumed. Node exposes no scalar-mult primitive and
// this is the only way to check the vector end-to-end instead of skipping it.
const P = 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffffn;
const A = P - 3n;
const B = 0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604bn;
const GX = 0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296n;
const GY = 0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5n;

const mod = (x) => ((x % P) + P) % P;
function powMod(base, exp) {
  let r = 1n, b = mod(base), e = exp;
  while (e > 0n) { if (e & 1n) r = (r * b) % P; b = (b * b) % P; e >>= 1n; }
  return r;
}
function ecAdd(p1, p2) {
  if (p1 === null) return p2;
  if (p2 === null) return p1;
  const [x1, y1] = p1, [x2, y2] = p2;
  if (x1 === x2 && mod(y1 + y2) === 0n) return null;
  const lam = x1 === x2 && y1 === y2
    ? mod((3n * x1 * x1 + A) * powMod(2n * y1, P - 2n))
    : mod((y2 - y1) * powMod(x2 - x1, P - 2n));
  const x3 = mod(lam * lam - x1 - x2);
  return [x3, mod(lam * (x1 - x3) - y1)];
}
function ecMul(k, point) {
  let result = null, addend = point, n = k;
  while (n > 0n) { if (n & 1n) result = ecAdd(result, addend); addend = ecAdd(addend, addend); n >>= 1n; }
  return result;
}
const onCurve = ([x, y]) => mod(y * y) === mod(x * x * x + A * x + B);
const compress = ([x, y]) =>
  Buffer.concat([Buffer.from([y % 2n === 0n ? 0x02 : 0x03]), Buffer.from(x.toString(16).padStart(64, '0'), 'hex')]);

// ── ECDSA P-256 in BigInt (FIPS 186-5 §6.4.2) ────────────────────────────────

const N = 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551n;
const HALF_N = N / 2n; // n is odd, so S <= n/2 means S <= (n-1)/2
const beToBig = (buf) => BigInt('0x' + (Buffer.from(buf).toString('hex') || '0'));
const bigToBe32 = (x) => Buffer.from(x.toString(16).padStart(64, '0'), 'hex');
function powModN(base, exp) {
  let r = 1n, b = ((base % N) + N) % N, e = exp;
  while (e > 0n) { if (e & 1n) r = (r * b) % N; b = (b * b) % N; e >>= 1n; }
  return r;
}

// SEC1 compressed point -> affine point, or null if it is not one.
function decompress(buf) {
  if (buf.length !== 33 || (buf[0] !== 0x02 && buf[0] !== 0x03)) return null;
  const x = beToBig(buf.subarray(1));
  if (x >= P) return null;
  const y2 = mod(x * x * x + A * x + B);
  let y = powMod(y2, (P + 1n) / 4n); // P ≡ 3 (mod 4)
  if (mod(y * y) !== y2) return null;
  if ((y & 1n) !== BigInt(buf[0] & 1)) y = P - y;
  return [x, y];
}

// Why a §5.4.7 verifier rejects this raw R||S, or null if it does not.
function p256StrictReason(sig) {
  if (sig.length !== 64) return 'signature is not 64 bytes';
  const r = beToBig(sig.subarray(0, 32)), s = beToBig(sig.subarray(32));
  if (r === 0n || s === 0n) return 'R or S is zero';
  if (r >= N || s >= N) return 'R or S >= n';
  if (s > HALF_N) return 'S > n/2 (high S)';
  return null;
}

// The ECDSA verification equation with e = digest (RFC-AITP-0001 §5.4.6: the
// digest is the hashed message and is not hashed again). Range-checked, but
// with no low-S rule: on its own this is the lax profile.
function p256EquationHolds(point, digest, sig) {
  const r = beToBig(sig.subarray(0, 32)), s = beToBig(sig.subarray(32));
  if (r < 1n || r >= N || s < 1n || s >= N) return false;
  const e = beToBig(digest);
  const w = powModN(s, N - 2n);
  const x = ecAdd(ecMul((e * w) % N, [GX, GY]), ecMul((r * w) % N, point));
  return x !== null && x[0] % N === r;
}

const p256NodeKey = ([x, y]) => createPublicKey({
  format: 'jwk', key: { kty: 'EC', crv: 'P-256', x: b64uEncode(bigToBe32(x)), y: b64uEncode(bigToBe32(y)) },
});
// ES256 over the pre-hash input, which is the same computation as ECDSA with
// e = sha256(preimage). Node's ECDSA always hashes, so it is handed the preimage.
const p256NodeVerify = (point, preimage, sig) =>
  cryptoVerify('sha256', preimage, { key: p256NodeKey(point), dsaEncoding: 'ieee-p1363' }, sig);

// Lax P-256: what a stock ES256 verifier accepts. Both implementations must agree.
function p256VerifyLax(point, preimage, sig) {
  const bigOk = p256EquationHolds(point, sha256(preimage), sig);
  const nodeOk = p256NodeVerify(point, preimage, sig);
  if (bigOk !== nodeOk) {
    throw new Error(`P-256 implementations disagree: BigInt equation says ${bigOk}, crypto.verify says ${nodeOk}`);
  }
  return bigOk;
}

// Strict P-256 (RFC-AITP-0001 §5.4.7) over d = sha256(preimage), with e = d.
function p256Verify(point, preimage, sig) {
  if (p256StrictReason(sig) !== null) return false;
  return p256VerifyLax(point, preimage, sig);
}

// ── algorithm-tagged AIDs and signatures (RFC-AITP-0001 §5.3, §5.4.3) ────────

// AID -> { alg, raw, point? }. Untagged `aid:pubkey:<43>` is Ed25519.
function aidKey(aid) {
  if (typeof aid !== 'string' || !aid.startsWith('aid:pubkey:')) {
    throw new Error(`not an aid:pubkey: identifier: ${JSON.stringify(aid)}`);
  }
  const rest = aid.slice('aid:pubkey:'.length);
  if (rest.startsWith('p256:')) {
    const raw = b64uDecode(rest.slice('p256:'.length), 33, `public key in ${aid}`);
    const point = decompress(raw);
    if (!point) throw new Error(`${aid} is not a valid SEC1 compressed P-256 point`);
    return { alg: 'p256', raw, point };
  }
  return { alg: 'ed25519', raw: aidRawKey(aid) };
}

// `p256.<86>`, `ed25519.<86>`, or untagged `<86>` (Ed25519) -> { alg, raw }.
function parseSignature(str, what) {
  if (typeof str !== 'string') throw new Error(`${what}: not a string: ${JSON.stringify(str)}`);
  let alg = 'ed25519', body = str;
  if (str.startsWith('p256.')) { alg = 'p256'; body = str.slice('p256.'.length); }
  else if (str.startsWith('ed25519.')) body = str.slice('ed25519.'.length);
  if (body.length !== 86) throw new Error(`${what}: signature body is ${body.length} chars, expected 86`);
  return { alg, raw: b64uDecode(body, 64, what) };
}

// Strict verification of a JCS-profile or proof signature (RFC-AITP-0001
// §5.4.6): d = sha256(preimage); Ed25519 signs d, P-256 uses e = d.
function verifySingleHash(aid, preimage, sigStr, what = 'signature') {
  const key = aidKey(aid);
  const sig = parseSignature(sigStr, what);
  if (sig.alg !== key.alg) {
    throw new Error(`${what} is tagged ${sig.alg} but ${aid} is a ${key.alg} key`);
  }
  if (key.alg === 'p256') return p256Verify(key.point, preimage, sig.raw);
  return ed25519Verify(key.raw, sha256(preimage), sig.raw);
}

// A double-hash negative (e = sha256(sha256(preimage))) is only meaningful if it
// really is a valid signature under that reading. Assert both halves.
function assertDoubleHashNegative(aid, preimage, sigStr, what) {
  if (verifySingleHash(aid, preimage, sigStr, what)) {
    throw new Error(`${what} verifies over the single-hash input — it is not a negative at all`);
  }
  if (!verifySingleHash(aid, sha256(preimage), sigStr, what)) {
    throw new Error(`${what} does not verify under the double-hash reading either, so it proves nothing about §5.4.6`);
  }
}

// ── the signing-input rule ───────────────────────────────────────────────────
//
// The three wrapped JCS-profile artifacts are transported inside a JSON object
// whose key names the artifact (RFC-AITP-0001 §5.4.1). That key is transport
// routing metadata and is never signed. Each vector declares which of the two
// its pinned bytes are, and this table is what the declaration is checked
// against — a vector cannot certify its own convention.

const ARTIFACT_WRAPPERS = new Set(['manifest', 'revocation_list', 'session_bundle']);

// The three JCS-profile artifact vectors. For these the answer is not a matter of
// declaration: RFC-AITP-0001 §5.4.1 requires the inner artifact body, so anything
// else is non-conformant however the vector describes itself.
const JCS_ARTIFACT_VECTORS = new Set(['kat-manifest-001', 'kat-revocation-001', 'kat-session-bundle-001']);

function declaredSigningInput(vector) {
  const decl = vector.signing_input;
  if (decl === undefined) {
    throw new Error(
      `vector has an "object" but no "signing_input" declaration. Every vector ` +
      `carrying pinned canonical bytes MUST state whether those bytes are the ` +
      `inner artifact body ("body") or the transport envelope ("envelope").`);
  }
  if (decl !== 'body' && decl !== 'envelope') {
    throw new Error(`signing_input must be "body" or "envelope", got ${JSON.stringify(decl)}`);
  }
  if (decl === 'envelope' && JCS_ARTIFACT_VECTORS.has(vector.id)) {
    throw new Error(
      `signing_input is "envelope", but this is a JCS-profile artifact whose signing ` +
      `input is the inner body (RFC-AITP-0001 §5.4.1, RFC-AITP-0003 §6.1, ` +
      `RFC-AITP-0008 §1.5, RFC-AITP-0010 §3). Pinning the transport wrapper is the ` +
      `defect corrected in the v0.2 signing-input change (see CHANGELOG.md); it must ` +
      `not be reintroduced. If the wrapper ` +
      `really must be pinned, that is an RFC change, not a vector change.`);
  }
  return decl;
}

// Returns { signed, alternative, wrapperKey } for a vector's `object`.
function shapes(vector) {
  const obj = vector.object;
  // A wrapper key counts wherever it appears, not only in first position: the
  // wire revocation envelope is {"revocation_list": …, "signature": …} and JSON
  // member order is not significant, so a pasted-in envelope must be caught
  // regardless of which member happens to come first. No inner artifact body
  // has a member named after an artifact, so this cannot false-positive.
  const wrapperKey = Object.keys(obj).find((k) => ARTIFACT_WRAPPERS.has(k)) ?? null;
  const decl = declaredSigningInput(vector);

  if (decl === 'envelope') {
    if (!wrapperKey) throw new Error(`signing_input "envelope" but object has no artifact wrapper key`);
    return { signed: obj, alternative: obj[wrapperKey], wrapperKey };
  }
  // "body": the object IS the inner artifact body; the alternative is it wrapped.
  if (wrapperKey) {
    throw new Error(
      `signing_input "body" but the object is still wrapped in "${wrapperKey}". ` +
      `The pinned bytes must be the inner artifact body — see RFC-AITP-0001 §5.4.1.`);
  }
  const inferred = inferWrapperKey(vector.id);
  return { signed: obj, alternative: inferred ? { [inferred]: obj } : null, wrapperKey: inferred };
}

function inferWrapperKey(vectorId) {
  if (vectorId.includes('manifest')) return 'manifest';
  if (vectorId.includes('revocation')) return 'revocation_list';
  if (vectorId.includes('session-bundle')) return 'session_bundle';
  return null;
}

// ── checks ───────────────────────────────────────────────────────────────────

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

function checkKeypairs() {
  console.log('── keypairs.json: seed → public key → AID ──');
  const { vectors } = readJson(join(KAT, 'keypairs.json'));
  const byId = new Map(vectors.map((v) => [v.id, v]));
  assertContents('keypairs.json', byId, KEYPAIRS_EXPECTED);
  for (const v of vectors) {
    if (v.algorithm === 'p256') {
      check(`${v.id} scalar → SEC1 compressed point → AID`, () => {
        const d = BigInt('0x' + v.private_scalar_hex);
        const point = ecMul(d, [GX, GY]);
        if (!point) throw new Error('scalar multiplication produced the point at infinity');
        if (!onCurve(point)) throw new Error('derived point is not on P-256');
        const comp = compress(point);
        eq(comp.toString('hex'), v.pubkey_compressed_hex, 'compressed point');
        eq(b64uEncode(comp), v.pubkey_b64url, 'pubkey_b64url');
        eq(v.aid, `aid:pubkey:p256:${v.pubkey_b64url}`, 'aid');
        // The decompression every P-256 signature check relies on must invert this.
        const back = decompress(comp);
        if (!back || back[0] !== point[0] || back[1] !== point[1]) throw new Error('decompress(compress(Q)) !== Q');
      });
    } else {
      check(`${v.id} seed → Ed25519 public key → AID`, () => {
        const seed = Buffer.from(v.seed_hex, 'hex');
        if (seed.length !== 32) throw new Error(`seed is ${seed.length} bytes, expected 32`);
        const jwk = ed25519PublicFromSeed(seed).export({ format: 'jwk' });
        eq(jwk.x, v.pubkey_b64url, 'pubkey_b64url');
        if (v.untagged_aid !== undefined) {
          // The tagged-form entry: both spellings of the same key are pinned.
          eq(v.aid, `aid:pubkey:ed25519:${v.pubkey_b64url}`, 'aid (tagged)');
          eq(v.untagged_aid, `aid:pubkey:${v.pubkey_b64url}`, 'untagged_aid');
        } else {
          eq(v.aid, `aid:pubkey:${v.pubkey_b64url}`, 'aid');
        }
      });
    }
  }
  check('kat-keypair-001-tagged is the same keypair as kat-keypair-001', () => {
    const tagged = byId.get('kat-keypair-001-tagged'), plain = byId.get('kat-keypair-001');
    if (!tagged || !plain) throw new Error('one of the two entries is missing');
    eq(tagged.seed_hex, plain.seed_hex, 'seed_hex');
    eq(tagged.pubkey_b64url, plain.pubkey_b64url, 'pubkey_b64url');
    eq(tagged.untagged_aid, plain.aid, 'untagged_aid');
    if (tagged.aid === plain.aid) throw new Error('tagged and untagged AIDs are the same string');
  });
  return byId;
}

